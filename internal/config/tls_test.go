package config

import (
	"os"
	"path/filepath"
	"testing"

	"github.com/stretchr/testify/assert"
	"github.com/stretchr/testify/require"
)

func TestTLSConfigFromYAML(t *testing.T) {
	dir := t.TempDir()
	certFile := filepath.Join(dir, "server.crt")
	keyFile := filepath.Join(dir, "server.key")
	require.NoError(t, os.WriteFile(certFile, []byte("fake-cert"), 0o600))
	require.NoError(t, os.WriteFile(keyFile, []byte("fake-key"), 0o600))

	yaml := `
server:
  host: "127.0.0.1"
  port: 8443
  tls:
    enabled: true
    cert_file: "` + certFile + `"
    key_file: "` + keyFile + `"
erpnext:
  base_url: "http://frappe.test"
  api_key: "k"
  api_secret: "s"
`
	configFile := filepath.Join(dir, "config.yaml")
	require.NoError(t, os.WriteFile(configFile, []byte(yaml), 0o600))
	t.Setenv("CONFIG_FILE", configFile)

	cfg, err := Load()
	require.NoError(t, err)
	assert.True(t, cfg.Server.TLS.Enabled)
	assert.Equal(t, certFile, cfg.Server.TLS.CertFile)
	assert.Equal(t, keyFile, cfg.Server.TLS.KeyFile)
}

